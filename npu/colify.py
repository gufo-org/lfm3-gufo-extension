"""Append an eight-column copy of a one-column GEMV pipeline to npu_gemv.loom.

Usage: colify.py <source def> <new def> <wrapper prefix> [--check]
Column c gets tiles [c, 2..4] and records [c * per, (c + 1) * per).
"""
import sys

path = 'npu_gemv.loom'
src_name, new_name, prefix = sys.argv[1:4]
check = '--check' in sys.argv
src = open(path).read()
head = f'pipeline.def<kernel> @{src_name}(%k: index, %rows: index, %records: index)'
start = src.index(head)
end = src.index('\n}\n', start) + 3
body = src[start:end].replace(
    head, f'pipeline.def<kernel> @{new_name}(%k: index, %rows: index, %records: index, %column: index)')
for r in '2345':
    body = body.replace(f'[0, {r}]', f'[%column, {r}]')


def once(text, old, new):
    assert text.count(old) == 1, old
    return text.replace(old, new)


body = once(body, '  %two = index.constant 2 : index\n',
            '  %two = index.constant 2 : index\n  %first = index.mul %column, %records : index\n')
body = once(body, 'func.call @fill_weights(%k, %rows, %record, ',
            '%global_w = index.add %first, %record : index\n      func.call @fill_weights(%k, %rows, %global_w, ')
body = once(body, '      %out_index = index.mul %record, %y_bytes_i : index',
            '      %global_y = index.add %first, %record : index\n      %out_index = index.mul %global_y, %y_bytes_i : index')
consts = '\n'.join(f'  %c{i} = index.constant {i} : index' for i in range(8))
composes = '\n'.join(
    f'  pipeline.compose @{new_name}[%k, %rows, %per, %c{i}](%x, %w, %y) : '
    '[index, index, index, index](buffer, buffer, buffer)' for i in range(8))


def wrapper(m):
    return f'''pipeline.def<kernel> public retain target(@npu) @{prefix}_k2048_m{m}() run(%x: buffer, %w: buffer, %y: buffer) {{
  %k = index.constant 2048 : index
  %rows = index.constant 4 : index
  %per = index.constant {m // 4 // 8} : index
{consts}
{composes}
}}
'''


tail = f'''
check.case public @{prefix}_k2048_m8192_case {{
  %s7 = check.literal value(7) : i64
  %s8 = check.literal value(8) : i64
  %x = check.generate.random.uniform seed(%s7) range(-1.0 to 1.0) : tensor<2048xbf16>
  %w = check.generate.random.uniform seed(%s8) range(-1.0 to 1.0) : tensor<8192x2048xbf16>
  %y = check.generate.fill value(0.0) : tensor<8192xf32>
  kernel.launch @{prefix}_k2048_m8192(%x, %w, %y) : (tensor<2048xbf16>, tensor<8192x2048xbf16>, tensor<8192xf32>)
  check.return
}}

check.benchmark<@{prefix}_k2048_m8192_case> @{prefix}_k2048_m8192_time
'''
if check:
    tail += f'''
check.scenario public @{prefix}_k2048_m256_check {{
  check.trial[1](%trial: index, %entropy: check.entropy) {{
    %seed = check.entropy.read %entropy[%trial] : check.entropy -> i64
    %x = check.generate.random.uniform seed(%seed) range(-1.0 to 1.0) : tensor<2048xbf16>
    %w = check.generate.random.uniform seed(%seed) range(-1.0 to 1.0) : tensor<256x2048xbf16>
    %y = check.generate.fill value(0.0) : tensor<256xf32>
    check.compare<@{prefix}_k2048_m256, @gemv_k2048_m256_reference>(%x, %w, %y) : (tensor<2048xbf16>, tensor<256x2048xbf16>, tensor<256xf32>) -> () {{
      check.expect.approximate actual(%y) expected(%y) atol(0.05) rtol(0.02) nan(same) : tensor<256xf32>, tensor<256xf32>
    }}
  }}
  check.return
}}
'''
out = (f'\n// Eight-column copy of @{src_name}, generated by colify.py.\n' + body + '\n'
       + wrapper(8192) + '\n' + (wrapper(256) if check else '') + tail)
open(path, 'a').write(out)
